export const PATIENT_TEXT: Record<Lang, PatientText> = { en, ar };

// An error message in the patient's language: known messages are translated,
// anything else becomes the generic message (never half-English in Arabic).
export function patientError(message: string | undefined, lang: Lang) {
  if (!message) return PATIENT_TEXT[lang].errors.generic;
  if (lang === "en") return message;
  return PATIENT_TEXT.ar.errors[message] ?? PATIENT_TEXT.ar.errors.generic;
}

const WEEKDAYS_EN = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
const WEEKDAYS_AR = ["الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت", "الأحد"];

// Plan day labels: "Monday" -> "الاثنين", "Day 3" -> "اليوم 3", "Every day" -> "كل يوم".
export function dayName(label: string, lang: Lang) {
  if (lang === "en") return label;
  const i = WEEKDAYS_EN.indexOf(label);
  if (i >= 0) return WEEKDAYS_AR[i];
  if (label === "Every day") return "كل يوم";
  const m = label.match(/^Day (\d+)$/);
  return m ? `اليوم ${m[1]}` : label;
}

export function formatDateIn(value: string, lang: Lang) {
  const d = value.length === 10 ? new Date(`${value}T00:00:00Z`) : new Date(value);
  return d.toLocaleDateString(DATE_LOCALE[lang], { day: "numeric", month: "long", year: "numeric", ...(value.length === 10 ? { timeZone: "UTC" } : {}) });
}

export function shortDayIn(date: string, lang: Lang) {
  return new Date(`${date}T00:00:00Z`).toLocaleDateString(DATE_LOCALE[lang], { weekday: "long", day: "numeric", month: "long", timeZone: "UTC" });
}

export function formatWhenIn(iso: string, timeZone: string, lang: Lang) {
  return new Date(iso).toLocaleString(DATE_LOCALE[lang], { weekday: "long", day: "numeric", month: "long", hour: "2-digit", minute: "2-digit", hourCycle: "h23", timeZone });
}

